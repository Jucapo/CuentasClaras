// Builds the self-hosted Material Symbols Rounded subset (spec §13.3) from the icon catalog.
// Run `npm run icons:build` after changing the catalog or the interface icons and commit both outputs;
// the app build never runs this script, so it needs no network.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';
import { ICON_CATALOG, UI_ICONS } from '../src/app/shared/ui/icons/icon-catalog.ts';

interface SourceFile {
  readonly path: string;
  readonly sha256: string;
}

/** Pinned commit of github.com/google/material-design-icons. */
const COMMIT = '10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7';
const FONT: SourceFile = {
  path: 'variablefont/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf',
  sha256: '7e74e36533ccee12c2b81e75bfcf3ccf123d3bb7e7e46d65d94445f23db0c97c',
};
const CODEPOINTS: SourceFile = {
  path: 'variablefont/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].codepoints',
  sha256: 'a7404d9e5a1b63f496cf05ace45d386075886b5a7f123fba9f29527cb6006fde',
};
/** Pinned axes; FILL stays variable so badges can use filled icons. */
const PINNED_AXES = { wght: 400, GRAD: 0, opsz: 24 };

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE_DIR = join(ROOT, 'node_modules', '.cache', 'material-symbols', COMMIT);
const FONT_OUTPUT = join(ROOT, 'public', 'fonts', 'material-symbols-rounded.woff2');
const MAP_OUTPUT = join(
  ROOT,
  'src',
  'app',
  'shared',
  'ui',
  'icons',
  'icon-codepoints.generated.ts',
);

async function load(source: SourceFile): Promise<Buffer> {
  const cached = join(CACHE_DIR, basename(source.path));
  let data: Buffer;
  try {
    data = await readFile(cached);
  } catch {
    const url = `https://raw.githubusercontent.com/google/material-design-icons/${COMMIT}/${source.path
      .split('/')
      .map(encodeURIComponent)
      .join('/')}`;
    console.log(`Downloading ${url}`);
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`Download failed (${response.status}): ${url}`);
    }
    data = Buffer.from(await response.arrayBuffer());
    await mkdir(CACHE_DIR, { recursive: true });
    await writeFile(cached, data);
  }
  const sha256 = createHash('sha256').update(data).digest('hex');
  if (sha256 !== source.sha256) {
    throw new Error(
      `SHA-256 mismatch for ${source.path}: expected ${source.sha256}, got ${sha256}`,
    );
  }
  return data;
}

function parseCodepoints(text: string): Map<string, number> {
  const codepoints = new Map<string, number>();
  for (const line of text.split(/\r?\n/)) {
    const [name, hex] = line.trim().split(/\s+/);
    if (name && hex) {
      codepoints.set(name, Number.parseInt(hex, 16));
    }
  }
  return codepoints;
}

function codepointsModule(entries: readonly (readonly [string, number])[]): string {
  const lines = entries.map(([name, codepoint]) => {
    const key = /^[a-z_][a-z0-9_]*$/.test(name) ? name : `'${name}'`;
    return `  ${key}: 0x${codepoint.toString(16)},`;
  });
  return [
    `// Generated by \`npm run icons:build\` from google/material-design-icons@${COMMIT.slice(0, 12)}.`,
    '// Do not edit: change the icon catalog and run the script again.',
    '',
    '/** Codepoint of every icon in the self-hosted font subset. */',
    'export const ICON_CODEPOINTS = {',
    ...lines,
    '} as const;',
    '',
    '/** Name of an icon available in the font subset. */',
    'export type IconName = keyof typeof ICON_CODEPOINTS;',
    '',
  ].join('\n');
}

async function main(): Promise<void> {
  const names = [
    ...new Set([...ICON_CATALOG.flatMap((group) => group.icons.map((i) => i.name)), ...UI_ICONS]),
  ].sort();

  const codepoints = parseCodepoints((await load(CODEPOINTS)).toString('utf8'));
  const missing = names.filter((name) => !codepoints.has(name));
  if (missing.length > 0) {
    throw new Error(`Unknown Material Symbols: ${missing.join(', ')}`);
  }
  const entries = names.map((name) => [name, codepoints.get(name) ?? 0] as const);

  const font = await load(FONT);
  const text = [...new Set(entries.map(([, codepoint]) => codepoint))]
    .map((codepoint) => String.fromCodePoint(codepoint))
    .join('');
  const subset = await subsetFont(font, text, {
    targetFormat: 'woff2',
    variationAxes: PINNED_AXES,
    // Icons render by codepoint, so the ligature tables are not needed.
    keepFeatures: [],
  });

  await mkdir(dirname(FONT_OUTPUT), { recursive: true });
  await writeFile(FONT_OUTPUT, subset);
  await writeFile(MAP_OUTPUT, codepointsModule(entries));
  const kilobytes = (subset.byteLength / 1024).toFixed(1);
  console.log(`${names.length} icons → ${FONT_OUTPUT} (${kilobytes} kB)`);
}

await main();
