// Single source of the icons (spec §13.3): the pickers read it and `npm run icons:build` subsets the
// font from it. Plain, dependency-free TypeScript so the build script can import it with Node.

/** An icon users can pick for categories, accounts and spaces. */
export interface CatalogIcon {
  /** Material Symbols name; it is also the key stored in the database. */
  readonly name: string;
  /** Spanish name shown as the accessible label. */
  readonly label: string;
  /** Spanish search terms besides the label. */
  readonly keywords: readonly string[];
}

/** A group of the icon catalog. */
export interface IconGroup {
  readonly id: string;
  readonly label: string;
  /** Icon of the group in the menus that jump to it; one of its icons. */
  readonly icon: string;
  readonly icons: readonly CatalogIcon[];
}

function icon(name: string, label: string, keywords = ''): CatalogIcon {
  return { name, label, keywords: keywords.split(' ').filter(Boolean) };
}

